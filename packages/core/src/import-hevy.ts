import type { Routine, RoutineExercise, CustomExercise } from '../../contract/domain/state-doc'
import type { ExerciseIndex } from './exercises'
import type { ImportOptions, ImportCustom, ImportSet, ImportEntry, ImportWorkout, ImportBodyweight, WorkoutImport, BodyweightImport } from './import-csv'
// The API is external JSON. These assertions describe fields consumed by the legacy parser;
// they deliberately do not sanitize/coerce the source graph, preserving hostile-input behavior.
interface HevyTemplate { id: string; title?: string; primary_muscle_group?: string; type?: string }
interface HevySet { type?: string; weight_kg?: number | null; reps?: number | null; duration_seconds?: number | null; distance_meters?: number | null; rpe?: number | null }
interface HevyExercise { exercise_template_id?: string; title?: string; sets?: HevySet[]; notes?: unknown; superset_id?: string | number | null }
interface HevyWorkout { id?: string; title?: string; start_time?: unknown; end_time?: unknown; exercises?: HevyExercise[] }
interface HevyRoutine { id?: string; title?: string; exercises?: HevyExercise[] }
interface HevyMeasurement { date?: string; weight_kg?: number; created_at?: string }
// As with CSV entries, a prior custom row contributes an unchecked, uncoerced ID.
export interface ImportRoutineConfig<Id = unknown> extends Omit<RoutineExercise, 'id'> { id: Id; sets: number; min?: number; speed?: number; sec?: number; weight?: number; mode?: 'reps' | 'time' | 'cardio'; reps?: number; warmupSets?: number; note?: string; sg?: string }
export interface ImportRoutine<Id = unknown> extends Omit<Routine, 'ex'> { id: string; name: string; emoji?: string; hevyId?: unknown; ex: ImportRoutineConfig<Id>[] }
export interface RoutineImport<Id = unknown> { kind: 'routines'; source: string; routines: ImportRoutine<Id>[]; customEx: ImportCustom[]; matched: number; created: number; unmatchedNames: string[]; exerciseCount: number; converted: boolean }
export interface RoutineImportState { customEx?: CustomExercise[]; routines?: Routine[] }
interface HevyDay { d: string; ex: Map<string, ImportSet[]>; name: string; start: number; end: number | null }
// Import a Hevy account through the public API (https://api.hevyapp.com/docs/).
//
// Exercise identity is Hevy's `exercise_template_id`, looked up in the generated
// `hevy-id-map.js` table — never the localized title on a set. Regenerate the map
// with `node scripts/build-hevy-id-map.mjs`. The API key never leaves this module's
// callers: nothing here stores it.

