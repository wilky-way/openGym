import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
let core: typeof import('../src/i18n-core.js')
beforeEach(async () => { vi.resetModules(); core = await import('../src/i18n-core.js'); vi.useFakeTimers() })
afterEach(() => { core._setDetailsLoader(null); vi.useRealTimers() })
const ex = { id: 'synthetic-exercise', st: ['Own steps'], desc: 'Own description' }
describe('English lazy details', () => {
  it('shares the first request, retaining custom fallback until English packs arrive', () => {
    const load = vi.fn()
    core._setDetailsLoader(load)
    expect(core.instrFor(ex)).toEqual(ex.st)
    expect(core.descFor(ex)).toBe(ex.desc)
    expect(load).toHaveBeenCalledTimes(1)
    const before = core.getVersion()
    expect(core._setDetails({[ex.id]:['Catalogue steps']}, {[ex.id]:'Catalogue description'}, null)).toBe(true)
    expect(core.getVersion()).toBe(before+1)
    expect(core.instrFor(ex)).toEqual(['Catalogue steps'])
    expect(core.descFor(ex)).toBe('Catalogue description')
    expect(core.instrTranslated(ex)).toBe(false)
    expect(core.descFor(undefined)).toBe('')
  })
  it('is not mistaken for no steps: tried again on the next ask after a pause', () => {
    const load = vi.fn(() => core._detailsFailed())
    core._setDetailsLoader(load)
    core.instrFor(ex)
    core.instrFor(ex)
    expect(load).toHaveBeenCalledTimes(1)
    vi.advanceTimersByTime(20000)
    expect(load).toHaveBeenCalledTimes(1)
    core.instrFor(ex)
    expect(load).toHaveBeenCalledTimes(2)
  })
  it('tried again as soon as the browser is back online', () => {
    const load = vi.fn(() => core._detailsFailed())
    core._setDetailsLoader(load)
    core.instrFor(ex)
    expect(load).toHaveBeenCalledTimes(1)
    // W01's browser listener invokes this approved shell-to-core hook.
    core._retryDetails()
    expect(load).toHaveBeenCalledTimes(2)
  })
  it('cancels old retry timers when replacing loaders and after successful packs', () => {
    const load = vi.fn(() => core._detailsFailed(10))
    core._setDetailsLoader(load)
    core.instrFor(ex)
    core._setDetails({}, {}, null)
    vi.advanceTimersByTime(10)
    core.instrFor(ex)
    expect(load).toHaveBeenCalledTimes(1)
    core._setDetailsLoader(null)
    expect(vi.getTimerCount()).toBe(0)
  })
})
